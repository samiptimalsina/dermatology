    /**
     * @return array<string, string>
     */
    public static function menuIconOptions(): array
    {
        $options = array_combine(self::MENU_ICONS, array_map('ucfirst', self::MENU_ICONS));

        foreach (self::MATERIAL_MENU_ICONS as $icon) {
            $options['material:'.$icon] = ucwords(str_replace('_', ' ', $icon));
        }

        return $options;
    }

